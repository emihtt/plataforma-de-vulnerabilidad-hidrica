"""Prueba reproducible de la candidata servida en localhost (requiere Playwright)."""
import json
import re
import sys
import hashlib
from datetime import datetime, timezone
from pathlib import Path
from playwright.sync_api import sync_playwright

BASE = sys.argv[1] if len(sys.argv) > 1 else 'http://127.0.0.1:4173/'
OUT = Path(__file__).resolve().parents[2] / 'evidencia'
OUT.mkdir(exist_ok=True)
report = {'url': BASE, 'checked_utc': datetime.now(timezone.utc).isoformat(), 'checks': [], 'pageerrors': [], 'external_failures': []}

with sync_playwright() as p:
    browser = p.chromium.launch(args=['--enable-webgl', '--use-gl=angle', '--use-angle=swiftshader', '--enable-unsafe-swiftshader'])
    context = browser.new_context(viewport={'width': 1366, 'height': 900}, locale='es-MX')
    report['index_sha256'] = hashlib.sha256(context.request.get(BASE).body()).hexdigest()
    page = context.new_page()
    page.on('pageerror', lambda e: report['pageerrors'].append(str(e)))
    page.on('requestfailed', lambda r: report['external_failures'].append(r.url) if not r.url.startswith(BASE) else None)
    page.goto(BASE)
    page.get_by_role('heading', name='Entender el agua empieza en el territorio.').wait_for()
    page.wait_for_timeout(1000)
    page.screenshot(path=str(OUT / 'demo-portada-desktop.png'))
    assert page.locator('.territory-figure path').count() >= 2
    report['checks'].append('Portada: geometria local y datos censales visibles')
    page.get_by_role('button', name=re.compile('Comenzar recorrido')).click()
    page.get_by_role('button', name='Ir al mapa →').click()
    page.locator('.maplibregl-canvas').wait_for()
    page.wait_for_timeout(1500)
    page.screenshot(path=str(OUT / 'demo-mapa-desktop.png'))
    # Punto visible en la captura de referencia 1366x900: comprobar el clic del lienzo.
    page.mouse.click(815, 419)
    page.get_by_role('dialog').wait_for()
    page.keyboard.press('Escape')
    page.get_by_role('dialog').wait_for(state='hidden')
    report['checks'].append('Mapa: clic real sobre una localidad del lienzo abre su ficha')
    report['checks'].append('Recorrido: panorama -> mapa local WebGL')
    page.get_by_role('button', name='Abrir el caso →').click()
    dialog = page.get_by_role('dialog')
    dialog.wait_for()
    assert '73 de 436 (17 %)' in dialog.inner_text()
    assert '26 % a 58 %' in dialog.inner_text()
    assert 'no demuestra agua potable ni abasto garantizado' in dialog.inner_text()
    page.screenshot(path=str(OUT / 'demo-ficha-desktop.png'))
    page.keyboard.press('Shift+Tab')
    assert page.evaluate('document.activeElement.closest("[role=dialog]") !== null')
    page.get_by_role('button', name='Continuar: usos y futuro →').click()
    page.get_by_role('heading', name='Un piloto local. Una visión compartida.').wait_for()
    assert page.get_by_role('heading', name='Cobertura nacional y sostenibilidad').count() == 1
    report['checks'].append('Recorrido completo: ficha verificada, foco modal y hoja de ruta')
    page.get_by_role('button', name='Terminar recorrido').click()
    page.get_by_role('navigation', name='Secciones principales').get_by_role('button', name='Mapa', exact=True).click()
    page.get_by_role('searchbox', name='Encuentra una comunidad').fill('gabriel')
    page.get_by_role('button', name=re.compile('San Gabriel Ixtla')).click()
    dialog.wait_for()
    page.keyboard.press('Escape')
    dialog.wait_for(state='hidden')
    report['checks'].append('Mapa: busqueda por nombre, ficha y cierre con Escape')
    page.get_by_role('navigation', name='Secciones principales').get_by_role('button', name='Prioridades', exact=True).click()
    page.locator('.priority-results li').first.wait_for()
    assert page.locator('.priority-results li').count() == 66
    slider = page.get_by_role('slider', name='Peso de Sin agua entubada')
    slider.fill('70')
    page.get_by_role('button', name='Restablecer', exact=True).click()
    with page.expect_download() as download:
        page.get_by_role('button', name='Exportar la lista en CSV').click()
    download.value.save_as(str(OUT / 'prioridades-verificadas.csv'))
    assert len((OUT / 'prioridades-verificadas.csv').read_text(encoding='utf-8-sig').splitlines()) >= 69
    page.locator('main').evaluate('(e) => e.scrollTop = 0')
    page.screenshot(path=str(OUT / 'demo-prioridades-desktop.png'))
    report['checks'].append('Prioridad: 66 filas, pesos interactivos, restablecer y CSV descargado')
    for ruta in ['fuentes', 'agua', 'acerca', 'usos']:
        page.goto(BASE + '#/' + ruta)
        page.locator('main h1').wait_for()
        page.wait_for_timeout(300)
    report['checks'].append('Todas las secciones abren sin excepciones de pagina')
    mobile = browser.new_context(viewport={'width': 390, 'height': 844}, is_mobile=True, has_touch=True, locale='es-MX')
    mp = mobile.new_page()
    mp.on('pageerror', lambda e: report['pageerrors'].append(str(e)))
    mp.goto(BASE)
    mp.locator('main h1').wait_for()
    mp.screenshot(path=str(OUT / 'demo-portada-movil.png'))
    assert mp.evaluate('document.documentElement.scrollWidth <= innerWidth')
    mp.get_by_role('button', name=re.compile('Comenzar recorrido')).click()
    mp.get_by_role('button', name='Ir al mapa →').click()
    mp.locator('.maplibregl-canvas').wait_for()
    mp.wait_for_timeout(800)
    mp.screenshot(path=str(OUT / 'demo-mapa-movil.png'))
    mp.get_by_role('button', name='Abrir el caso →').click()
    mp.get_by_role('dialog').wait_for()
    mp.screenshot(path=str(OUT / 'demo-ficha-movil.png'))
    assert mp.locator('.ficha-body').evaluate('(e) => e.scrollWidth <= e.clientWidth')
    mp.get_by_role('button', name='Continuar: usos y futuro →').click()
    mp.get_by_role('button', name='Terminar recorrido').click()
    report['checks'].append('Movil 390x844: sin desborde y recorrido completo')
    # Carga nueva sin cache del navegador, bloqueando toda red externa.
    isolated = browser.new_context(service_workers='block', viewport={'width': 1366, 'height': 900})
    isolated.route('**/*', lambda r: r.continue_() if r.request.url.startswith(BASE) else r.abort())
    ip = isolated.new_page()
    ip.on('pageerror', lambda e: report['pageerrors'].append(str(e)))
    ip.goto(BASE)
    ip.locator('main h1').wait_for()
    ip.get_by_role('button', name='Explorar el mapa').click()
    ip.locator('.maplibregl-canvas').wait_for()
    ip.get_by_role('button', name=re.compile('San Gabriel Ixtla')).click()
    ip.get_by_role('dialog').wait_for()
    assert '26 % a 58 %' in ip.get_by_role('dialog').inner_text()
    ip.keyboard.press('Escape')
    ip.goto(BASE + '#/agua')
    ip.get_by_text('Sin dato: no hay conexión y este dispositivo no tiene una consulta guardada.', exact=True).wait_for()
    ip.screenshot(path=str(OUT / 'demo-sin-internet.png'))
    report['checks'].append('Sin internet externo y sin cache: portada, mapa local, ficha y falta de lluvia explicita')
    # PWA: visitar, instalar cache y recargar sin red alguna, incluido localhost.
    page.goto(BASE)
    page.evaluate('navigator.serviceWorker.ready')
    page.reload()
    page.wait_for_function('navigator.serviceWorker.controller !== null')
    context.set_offline(True)
    page.reload()
    page.locator('main h1').wait_for()
    page.get_by_role('button', name='Explorar el mapa').click()
    page.locator('.maplibregl-canvas').wait_for()
    page.get_by_role('button', name=re.compile('San Gabriel Ixtla')).click()
    page.get_by_role('dialog').wait_for()
    report['checks'].append('PWA: recarga y ficha con red completamente desconectada tras instalacion')
    context.set_offline(False)
    assert not report['pageerrors'], report['pageerrors']
    browser.close()

(OUT / 'pruebas-demo.json').write_text(json.dumps(report, indent=2, ensure_ascii=False), encoding='utf-8')
print(json.dumps(report, ensure_ascii=True, indent=2))
